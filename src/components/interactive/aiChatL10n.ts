export type Locale =
  | 'zh' | 'en' | 'ja' | 'ko' | 'es' | 'pt' | 'fr' | 'de' | 'ru'
  | 'ar' | 'fa' | 'th' | 'vi' | 'id' | 'fil' | 'hi' | 'tr';

