  fabOpen: string;
  /** 页面上下文提示条 */
  contextHint: string;
  /** 提示条 × 按钮 aria-label（点击 = 本次会话不再附带上下文） */
  contextDismiss: string;
  /** 发送时拼接的页面上下文前缀，{title} 为占位符 */
